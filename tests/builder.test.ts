import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { addNode, findNode, moveNode, moveSibling, newNode, parseUiTree, safeUrl, type UiTree } from "../lib/builder/tree";
import { exportToReact } from "../lib/code-generator";
import { strFromU8, strToU8, unzipSync, zipSync } from "fflate/browser";

const container = newNode("container");
const child = newNode("container");
const text = newNode("text");
text.props.text = '</script><img src=x onerror="alert(1)">';
let tree: UiTree = addNode({ nodes: [] }, "root", container);
tree = addNode(tree, container.id, child);
tree = addNode(tree, child.id, text);
assert.ok(parseUiTree(tree));
assert.equal(moveNode(tree, container.id, child.id), tree, "must reject moving a node into its own descendant");
const second = newNode("button");
tree = addNode(tree, "root", second);
assert.equal(moveSibling(tree.nodes, second.id, -1)[0].id, second.id);
assert.ok(findNode(tree.nodes, text.id));
assert.equal(safeUrl("javascript:alert(1)"), "");
assert.equal(safeUrl("//evil.example"), "");
assert.equal(safeUrl("/\\evil.example"), "");
assert.equal(safeUrl("https://example.com/a.png", true), "https://example.com/a.png");
assert.equal(parseUiTree({ nodes: [text, text] }), null, "duplicate node IDs are invalid");
const bad = structuredClone(tree);
bad.nodes[0].children[0].children[0].props.href = "javascript:alert(1)";
assert.equal(parseUiTree(bad), null);
const id = "aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee";
const web = exportToReact(tree, "web", id, "Test app");
const app = exportToReact(tree, "app", id, "Test app");
assert.equal(JSON.parse(web["src/tree.json"]).nodes[0].children[0].children[0].props.text, text.props.text);
assert.ok(!web["src/App.jsx"].includes("onerror"), "user content must stay data rather than code");
assert.ok(app["App.js"].includes("react-native"));
assert.equal(JSON.parse(app["eas.json"]).build.preview.android.buildType, "apk");
const zip = zipSync(Object.fromEntries(Object.entries(web).map(([name, content]) => [name, strToU8(content)])));
assert.equal(strFromU8(unzipSync(zip)["src/tree.json"]), web["src/tree.json"]);
const destination = process.env.EXPORT_TEST_DIR;
if (destination) for (const [path, content] of Object.entries(web)) { const full = join(destination, path); await mkdir(join(full, ".."), { recursive: true }); await writeFile(full, content); }
console.log("PASS: nested trees, safe URLs, cycle prevention, ordering, source isolation and ZIP export");
